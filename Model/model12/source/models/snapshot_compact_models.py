"""Create/check source-only snapshots for the new compact experiments."""
from pathlib import Path
import argparse
import hashlib
import json
import shutil

ROOT = Path(__file__).resolve().parents[1]


def source_files():
    files = [ROOT/name for name in ("README.md", "tsauc.py", "requirements.txt", "models/__init__.py",
             "models/download_training.py", "models/run_next_models.py", "models/report_next_models.py",
             "models/snapshot_compact_models.py", "models/validate_compact_serving.py", "tests/test_compact_models.py",
             "models/model9/__init__.py", "models/model9/pairwise_stack.py",
             "models/model10/__init__.py", "models/model10/config.py",
             "models/model10/causal_transforms.py", "models/model10/sources.py")]
    if (ROOT/"models/NEXT_RESULTS.md").exists():
        files.append(ROOT/"models/NEXT_RESULTS.md")
    for number in (11, 12, 13, 14, 15, 16):
        files.extend(path for path in (ROOT/f"models/model{number}").iterdir()
                     if path.is_file() and path.suffix in (".py", ".md", ".txt"))
    return sorted(files)


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("command", choices=("sync", "check"))
    args = parser.parse_args()
    files = source_files()
    expected = {str(path.relative_to(ROOT)): dict(sha256=digest(path), bytes=path.stat().st_size) for path in files}
    for number in (11, 12, 13, 14, 15, 16):
        directory = ROOT/f"models/model{number}/source"
        marker = directory/".generated-source-snapshot"
        if args.command == "sync":
            if directory.exists() and not marker.exists():
                raise RuntimeError(f"Refusing to overwrite an unmarked source directory: {directory}")
            directory.mkdir(parents=True, exist_ok=True)
            marker.write_text("Generated by models/snapshot_compact_models.py\n")
            for path in files:
                destination = directory/path.relative_to(ROOT)
                destination.parent.mkdir(parents=True, exist_ok=True)
                shutil.copy2(path, destination)
            (directory/"SOURCE_MANIFEST.json").write_text(json.dumps(expected, indent=2)+"\n")
            (directory/"SOURCE_README.md").write_text(
                "# Compact experiment source snapshot\n\n"
                "This mini-repository contains Models 11–16, the shared implementation,\n"
                "the exact scoring module and the minimal upstream loader dependencies.\n"
                "Training data, credentials, feature caches and fitted weights are excluded.\n"
                "Experiments require the upstream artifact paths documented by each model.\n"
                "Run commands from this directory so imports resolve.\n\n"
                "Refresh from the main workspace: `python3 models/snapshot_compact_models.py sync`.\n"
                "Check: `python3 models/snapshot_compact_models.py check`.\n")
        else:
            actual = json.loads((directory/"SOURCE_MANIFEST.json").read_text())
            if actual != expected:
                raise RuntimeError(f"Snapshot manifest is stale: Model {number}")
            for relative, entry in actual.items():
                if digest(directory/relative) != entry["sha256"]:
                    raise RuntimeError(f"Snapshot content mismatch: Model {number}/{relative}")
        print(f"Model {number}: {args.command} OK ({len(files)} source files)")


if __name__ == "__main__":
    main()
