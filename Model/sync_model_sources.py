"""Build and validate complete source snapshots for every numbered model.

The live experiment packages intentionally reuse repository-root modules and
earlier model packages.  This utility makes those dependencies visible inside
each ``models/model<N>/source`` directory without copying generated data,
caches, fitted weights, predictions, or logs.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import shutil
from pathlib import Path
from typing import Iterable


PROJECT_ROOT = Path(__file__).resolve().parents[1]
MODELS_ROOT = PROJECT_ROOT / "models"
SNAPSHOT_MARKER = ".generated-source-snapshot"
MANIFEST_NAME = "SOURCE_MANIFEST.json"

ROOT_SOURCE_NAMES = (
    "alternative_model_experiment.py",
    "build_submission_5.py",
    "build_submission_bundle.py",
    "competition_data.py",
    "ensemble_cv.py",
    "ensemble_training.py",
    "feature_pipeline.py",
    "feature_selection_experiment.py",
    "joint_lightgbm_experiment.py",
    "joint_training.py",
    "postprocess.py",
    "requirements.txt",
    "scoring.py",
    "solution.py",
    "stack_cv.py",
    "train_cv.py",
    "tsauc.py",
    "validate_submission.py",
)
MODEL_SOURCE_SUFFIXES = {".py", ".ipynb", ".md", ".sh", ".txt"}
HISTORICAL_SOURCE_SUFFIXES = MODEL_SOURCE_SUFFIXES | {".json", ".npz"}
HISTORICAL_RESEARCH_FILES = {
    1: ("ensemble_cv.py", "validate_submission.py", "build_submission_bundle.py"),
    2: ("ensemble_cv.py",),
    3: ("feature_selection_experiment.py",),
}


def _sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def _copy_file(source: Path, destination: Path) -> None:
    destination.parent.mkdir(parents=True, exist_ok=True)
    shutil.copy2(source, destination)


def _copy_tree_files(
    source_root: Path,
    destination_root: Path,
    *,
    suffixes: set[str],
    excluded_parts: Iterable[str] = (),
) -> None:
    excluded = set(excluded_parts)
    for source in sorted(source_root.rglob("*")):
        if not source.is_file() or source.suffix not in suffixes:
            continue
        relative = source.relative_to(source_root)
        if any(part in excluded for part in relative.parts):
            continue
        _copy_file(source, destination_root / relative)


def _numbered_models() -> tuple[int, ...]:
    numbers: list[int] = []
    for path in MODELS_ROOT.glob("model*"):
        suffix = path.name.removeprefix("model")
        if path.is_dir() and suffix.isdigit():
            numbers.append(int(suffix))
    return tuple(sorted(numbers))


def _write_snapshot_readme(stage: Path, model_number: int, kind: str) -> None:
    if kind == "historical_submission":
        layout = (
            "Manifested deployment files are copied byte-for-byte from the "
            f"historical `submissions/submission_{model_number}/` bundle. "
            "Current retained experiment/bundle drivers live under "
            "`research/`; they are useful provenance but are not claimed as "
            "historically exact because this workspace has no Git history. "
            "Run deployment commands from this directory so its flat Crunch "
            "imports resolve."
        )
        contents = (
            "The snapshot contains every recoverable deployment source file, "
            "the frozen non-model feature contracts when applicable, retained "
            "research drivers, documentation, and the explicitly identified "
            "reconstructed detector helper."
        )
    else:
        layout = (
            "This snapshot preserves the repository layout. Run commands from "
            "this directory; shared modules are at its root and experiment "
            "packages are below `models/`."
        )
        contents = (
            "The snapshot contains model and upstream package source, shared "
            "pipelines, notebooks, documentation, detector modules, and "
            "regression-test source."
        )
    content = f"""# Model {model_number} source snapshot

{layout}

{contents} It deliberately excludes `train/`, fitted models, feature matrices,
prediction checkpoints, caches, and run logs.

`{MANIFEST_NAME}` records the SHA-256 digest and byte size of every included
file. Rebuild all snapshots from the repository root with:

```bash
python3 models/sync_model_sources.py sync
python3 models/sync_model_sources.py check
```

Do not edit this generated directory directly. Change the canonical source and
run the sync command again.
"""
    # Keep a historical submission's own README.md intact.
    (stage / "SOURCE_README.md").write_text(content, encoding="utf-8")
    (stage / SNAPSHOT_MARKER).write_text(
        "Generated by models/sync_model_sources.py\n", encoding="utf-8"
    )


def _populate_historical(stage: Path, model_number: int) -> str:
    submission = PROJECT_ROOT / "submissions" / f"submission_{model_number}"
    if not submission.is_dir():
        raise FileNotFoundError(f"historical source bundle is missing: {submission}")
    _copy_tree_files(
        submission,
        stage,
        suffixes=HISTORICAL_SOURCE_SUFFIXES,
        excluded_parts={"resources", "train", "data", "prediction", "__pycache__"},
    )
    # The upload manifest describes generated resources, not source provenance.
    (stage / "bundle_manifest.json").unlink(missing_ok=True)
    for name in HISTORICAL_RESEARCH_FILES[model_number]:
        _copy_file(PROJECT_ROOT / name, stage / "research" / name)
    # The old bundles retained two unused detector ablations that import
    # channels18.py, but omitted that helper. Supply the audited later
    # reconstruction explicitly rather than leaving apparently complete source
    # with two modules that cannot be imported.
    _copy_file(
        PROJECT_ROOT / "detector" / "core" / "channels18.py",
        stage / "detector" / "channels18.py",
    )
    (stage / "RECONSTRUCTION.md").write_text(
        "# Reconstructed historical dependency\n\n"
        "The frozen submission omitted `detector/channels18.py`, even though "
        "its unused `detectors19.py` and `detectors20.py` ablations import it. "
        "The copy included here comes from the current audited "
        "`detector/core/channels18.py`; it is clearly supplemental and is not "
        "claimed to be the lost historical revision. The deployed Model 1–3 "
        "feature contracts never imported those two ablations.\n",
        encoding="utf-8",
    )
    return f"submissions/submission_{model_number}"


def _populate_experiment(stage: Path, model_number: int) -> str:
    for name in ROOT_SOURCE_NAMES:
        source = PROJECT_ROOT / name
        if not source.is_file():
            raise FileNotFoundError(f"shared source file is missing: {source}")
        _copy_file(source, stage / name)

    _copy_tree_files(
        PROJECT_ROOT / "detector",
        stage / "detector",
        suffixes={".py", ".md"},
        excluded_parts={"__pycache__"},
    )
    _copy_tree_files(
        PROJECT_ROOT / "tests",
        stage / "tests",
        suffixes={".py"},
        excluded_parts={"__pycache__"},
    )
    _copy_file(MODELS_ROOT / "__init__.py", stage / "models" / "__init__.py")

    # Model 5 builds on Model 4, and every later experiment may import any
    # earlier experiment package. Including the full lineage makes the snapshot
    # robust to those explicit imports while keeping generated output excluded.
    for dependency_number in range(4, model_number + 1):
        source_model = MODELS_ROOT / f"model{dependency_number}"
        if not source_model.is_dir():
            raise FileNotFoundError(f"model dependency is missing: {source_model}")
        _copy_tree_files(
            source_model,
            stage / "models" / source_model.name,
            suffixes=MODEL_SOURCE_SUFFIXES,
            excluded_parts={
                "source",
                ".source.building",
                "runs",
                "artifacts",
                "all_detector_artifacts",
                "__pycache__",
            },
        )
    return f"repository source plus models/model4..model{model_number}"


def _canonical_source(
    relative: str, model_number: int, kind: str
) -> str | None:
    """Return the repository-relative canonical source for a copied file."""

    if relative in {SNAPSHOT_MARKER, "SOURCE_README.md", "RECONSTRUCTION.md"}:
        return None
    if kind == "historical_submission":
        if relative == "detector/channels18.py":
            return "detector/core/channels18.py"
        prefix = "research/"
        if relative.startswith(prefix):
            return relative.removeprefix(prefix)
        return f"submissions/submission_{model_number}/{relative}"
    return relative


def _manifest(
    stage: Path, model_number: int, provenance: str, kind: str
) -> dict[str, object]:
    files: dict[str, dict[str, object]] = {}
    for path in sorted(stage.rglob("*")):
        if not path.is_file() or path.name == MANIFEST_NAME:
            continue
        relative = path.relative_to(stage).as_posix()
        files[relative] = {
            "bytes": path.stat().st_size,
            "sha256": _sha256(path),
            "canonical_source": _canonical_source(relative, model_number, kind),
        }
    return {
        "schema_version": 1,
        "model": f"model{model_number}",
        "provenance": provenance,
        "generated_outputs_included": False,
        "file_count": len(files),
        "total_bytes": sum(int(item["bytes"]) for item in files.values()),
        "files": files,
    }


def build_snapshot(model_number: int) -> Path:
    """Atomically rebuild one model's generated source snapshot."""

    model_directory = MODELS_ROOT / f"model{model_number}"
    if not model_directory.is_dir():
        raise FileNotFoundError(f"model directory is missing: {model_directory}")
    destination = model_directory / "source"
    stage = model_directory / ".source.building"
    if stage.exists():
        shutil.rmtree(stage)
    stage.mkdir()

    try:
        if model_number <= 3:
            provenance = _populate_historical(stage, model_number)
            kind = "historical_submission"
        else:
            provenance = _populate_experiment(stage, model_number)
            kind = "experiment"
        _write_snapshot_readme(stage, model_number, kind)
        manifest = _manifest(stage, model_number, provenance, kind)
        (stage / MANIFEST_NAME).write_text(
            json.dumps(manifest, indent=2, sort_keys=True) + "\n", encoding="utf-8"
        )

        if destination.exists():
            if not (destination / SNAPSHOT_MARKER).is_file():
                raise RuntimeError(
                    f"refusing to replace unmarked source directory: {destination}"
                )
            shutil.rmtree(destination)
        stage.replace(destination)
    except BaseException:
        if stage.exists():
            shutil.rmtree(stage)
        raise
    return destination


def validate_snapshot(model_number: int) -> tuple[int, int]:
    """Validate one snapshot against its recorded path, size, and hash contract."""

    source = MODELS_ROOT / f"model{model_number}" / "source"
    manifest_path = source / MANIFEST_NAME
    if not (source / SNAPSHOT_MARKER).is_file() or not manifest_path.is_file():
        raise FileNotFoundError(f"model{model_number} has no complete source snapshot")
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    expected = manifest["files"]
    actual_paths = {
        path.relative_to(source).as_posix()
        for path in source.rglob("*")
        if path.is_file() and path.name != MANIFEST_NAME
    }
    if actual_paths != set(expected):
        missing = sorted(set(expected) - actual_paths)
        extra = sorted(actual_paths - set(expected))
        raise ValueError(
            f"model{model_number} source path mismatch; missing={missing}, extra={extra}"
        )
    for relative, contract in expected.items():
        path = source / relative
        if path.stat().st_size != int(contract["bytes"]):
            raise ValueError(f"size mismatch: {path}")
        if _sha256(path) != contract["sha256"]:
            raise ValueError(f"hash mismatch: {path}")
        canonical_relative = contract.get("canonical_source")
        if canonical_relative is not None:
            canonical = PROJECT_ROOT / canonical_relative
            if not canonical.is_file():
                raise FileNotFoundError(f"canonical source is missing: {canonical}")
            if canonical.stat().st_size != int(contract["bytes"]):
                raise ValueError(f"snapshot is stale relative to: {canonical}")
            if _sha256(canonical) != contract["sha256"]:
                raise ValueError(f"snapshot is stale relative to: {canonical}")
    return len(expected), sum(int(item["bytes"]) for item in expected.values())


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("command", choices=("sync", "check"))
    parser.add_argument(
        "--models",
        nargs="+",
        type=int,
        default=None,
        help="numbered models to process (default: every models/model<N> directory)",
    )
    arguments = parser.parse_args()
    numbers = tuple(arguments.models) if arguments.models else _numbered_models()
    if not numbers:
        raise SystemExit("no numbered model directories found")

    for number in numbers:
        if arguments.command == "sync":
            build_snapshot(number)
        count, size = validate_snapshot(number)
        print(f"model{number}: {count} files, {size / (1024 * 1024):.2f} MiB")


if __name__ == "__main__":
    main()
